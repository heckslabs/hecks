/// Whether an open word (a bind or binding verb, or a settings key) would reach a method Ruby
/// defines on every object, or one the builder keeps for itself.
pub fn is_ruby_method(word: &str) -> bool {
    RUBY_METHODS.contains(&word) || word.ends_with("_impl")
}

/// Whether one `::`-separated segment of a constant path is a host handle.
pub fn is_host_constant(segment: &str) -> bool {
    CONSTANTS.contains(&segment) || segment.starts_with("RUBY_")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_lists_are_sorted_so_a_review_sees_one_place_to_add() {
        for list in [RUBY_METHODS, PREDICATE_CALLS, CONSTANTS] {
            let mut sorted = list.to_vec();
            sorted.sort_unstable();
            assert_eq!(list, sorted.as_slice());
        }
    }

    #[test]
    fn a_builder_method_is_a_ruby_method() {
        assert!(is_ruby_method("system"));
        assert!(is_ruby_method("realm_impl"));
        assert!(!is_ruby_method("persisted_by"));
    }
}
