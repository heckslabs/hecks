//! `write_sidecars!` (`rust/project_rust_pipeline.rb`) — `ir.json` (the
//! exact bytes this crate's own optional-marking pass already produced,
//! never re-serialized again) and `metadata.rs` (`pub const IR_JSON: &str
//! = ...;`, using a Rust-string-literal-correct escaping of that same
//! exact text).
//!
//! R5 (`docs/audits/2026-08-11-bug-triage.md`) — this deliberately does
//! not reproduce Ruby's own `String#inspect` byte-for-byte, because
//! `.inspect`'s escaping is a landmine here: it escapes a literal
//! `#{`/`#@` as `\#{`/`\#@` (meaningful only when the inspected text is
//! later re-read as a Ruby double-quoted string) and a control character
//! as bare `\uXXXX` (Ruby's own escape, missing Rust's required braces)
//! — neither is a legal Rust escape, so a domain description containing
//! either, embedded verbatim in `ir.json`'s own JSON text, would make
//! the generated `metadata.rs` fail to compile. Ruby's own side avoids
//! the same bare `.inspect` call: `rust/project/naming.rb`'s
//! `RustProjection::Projector.rust_string_literal` builds the escaped
//! string itself instead. This function is that same algorithm, ported
//! to Rust rather than "Ruby's `.inspect`, replicated" — the two must
//! still match each other byte-for-byte
//! (`spec/hecks_build_pipeline_spec.rb`), just not Ruby's `.inspect`
//! itself.
pub fn rust_string_literal(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for ch in text.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 || (c as u32) == 0x7f => {
                out.push_str(&format!("\\u{{{:x}}}", c as u32));
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// `write_sidecars!` (Ruby) — writes `<mod_dir>/ir.json` (the exact
/// captured bytes) and `<mod_dir>/metadata.rs` (the embedded IR_JSON
/// constant), returning the two paths written for the caller's own
/// `puts`-equivalent logging.
pub fn write(mod_dir: &std::path::Path, ir_text: &str, source_label: &str) -> Result<(std::path::PathBuf, std::path::PathBuf), String> {
    std::fs::create_dir_all(mod_dir).map_err(|e| format!("creating {}: {e}", mod_dir.display()))?;

    let ir_json_path = mod_dir.join("ir.json");
    std::fs::write(&ir_json_path, ir_text).map_err(|e| format!("writing {}: {e}", ir_json_path.display()))?;

    let metadata_path = mod_dir.join("metadata.rs");
    let mut contents = String::new();
    // "GENERATED by bin/project_rust" — literal parity with both Ruby
    // pipelines (`rust/project/domain_generator.rb`'s default path and
    // `rust/project_rust_pipeline.rb`'s opt-in path both write this exact
    // text, not "hecks-build"), a deliberate choice: this crate's own
    // verification (`spec/hecks_build_pipeline_spec.rb`) proves its
    // output is byte-identical to the opt-in path's, and three different
    // attribution strings across three pipelines that all produce the
    // same artifact for the same bluebook would read as a real
    // divergence to anyone diffing generated trees, not a cosmetic one.
    contents.push_str("// GENERATED by bin/project_rust — ");
    contents.push_str(source_label);
    contents.push_str("'s own canonical IR,\n");
    contents.push_str("// embedded for runtime self-description. Not read by any dispatch\n");
    contents.push_str("// function in this module — introspection only.\n");
    contents.push_str("pub const IR_JSON: &str = ");
    contents.push_str(&rust_string_literal(ir_text));
    contents.push_str(";\n");
    std::fs::write(&metadata_path, contents).map_err(|e| format!("writing {}: {e}", metadata_path.display()))?;

    Ok((ir_json_path, metadata_path))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn escapes_quotes_backslashes_and_newlines() {
        assert_eq!(rust_string_literal("abc\ndef"), "\"abc\\ndef\"");
        assert_eq!(rust_string_literal("tab\there"), "\"tab\\there\"");
        assert_eq!(rust_string_literal("quote\"here"), "\"quote\\\"here\"");
        assert_eq!(rust_string_literal("back\\slash"), "\"back\\\\slash\"");
    }

    // R5 — the actual landmine: a literal `#{`/`#@` must pass through
    // unchanged (Rust has no string interpolation syntax to escape),
    // never Ruby's own `\#{`/`\#@` rendering (invalid Rust — no `\#`
    // escape exists at all).
    #[test]
    fn leaves_a_literal_hash_brace_and_hash_at_untouched() {
        assert_eq!(rust_string_literal("cost #{threshold}"), "\"cost #{threshold}\"");
        assert_eq!(rust_string_literal("ivar #@foo"), "\"ivar #@foo\"");
    }

    // R5 — a control character becomes a braced `\u{...}` (Rust's own
    // syntax), never Ruby's bare `\uXXXX` (no braces — also invalid Rust).
    #[test]
    fn escapes_control_characters_as_braced_lowercase_hex() {
        assert_eq!(rust_string_literal("\u{1}\u{1f}"), "\"\\u{1}\\u{1f}\"");
        assert_eq!(rust_string_literal("\u{7f}"), "\"\\u{7f}\"");
    }
}
