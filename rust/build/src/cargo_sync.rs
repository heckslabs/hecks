//! Rewrites the root `generated/mod.rs` and syncs `rust/Cargo.toml` `[features]`.
//! Ports `sync_mod_and_cargo!`, keeping its output byte-identical.

use std::path::Path;

// Both tables come from the reserved-word vocabularies via `hecks project_reserved_names`.
use crate::reserved_names::{CARGO_RESERVED_DOMAIN_NAMES, RUST_KEYWORDS};

/// True if `name` works as a directory, a bare Rust module identifier and a Cargo feature key.
pub fn valid_domain_mod_name(name: &str) -> bool {
    let mut chars = name.chars();
    let starts_ok = matches!(chars.next(), Some(c) if c == '_' || c.is_ascii_lowercase());
    let rest_ok = chars.all(|c| c == '_' || c.is_ascii_lowercase() || c.is_ascii_digit());
    starts_ok && rest_ok && !RUST_KEYWORDS.contains(&name) && !CARGO_RESERVED_DOMAIN_NAMES.contains(&name)
}

/// Lists the directories under `out_root`, and those with a `merged.rs` (activatable domains).
fn scan_generated_dirs(out_root: &Path) -> Result<(Vec<String>, Vec<String>), String> {
    let mut all_dirs = Vec::new();
    for entry in std::fs::read_dir(out_root).map_err(|e| format!("reading {}: {e}", out_root.display()))? {
        let entry = entry.map_err(|e| format!("reading {}: {e}", out_root.display()))?;
        if entry.file_type().map(|t| t.is_dir()).unwrap_or(false) {
            all_dirs.push(entry.file_name().to_string_lossy().to_string());
        }
    }
    all_dirs.sort();

    let domains = all_dirs.iter().filter(|name| out_root.join(name).join("merged.rs").is_file()).cloned().collect();

    Ok((all_dirs, domains))
}

/// Rewrites the root `mod.rs`: a `pub mod` per directory and an `active` re-export per domain.
///
/// Cargo has no mutually-exclusive features, so the default domain's re-export backs off when
/// another domain feature is on, and two non-default features hit an explicit `compile_error!`
/// instead of a duplicate-import E0252.
fn write_root_mod(out_root: &Path, all_dirs: &[String], domains: &[String], target_mod_name: &str) -> Result<(), String> {
    let mut out = String::new();
    out.push_str("// GENERATED by hecks project_rust — re-run it to refresh this list.\n");
    out.push_str("//\n");
    out.push_str("// BUG#25 — every DOMAIN (an entry in `domains`, below: a directory\n");
    out.push_str("// carrying its own merged.rs and therefore its own Cargo feature) is\n");
    out.push_str("// declared behind that SAME feature, so a broken or absent domain's\n");
    out.push_str("// generated code is never even compiled into a build that selects a\n");
    out.push_str("// DIFFERENT domain — `cargo build --features waybill` used to pull in\n");
    out.push_str("// every OTHER domain's `pub mod` unconditionally, so one domain's own\n");
    out.push_str("// non-compiling generated code (a `has_many` field, before this fix)\n");
    out.push_str("// broke every feature's build, not just its own. A shared FRAMEWORK\n");
    out.push_str("// chapter (governance/identity — no merged.rs of its own, so absent\n");
    out.push_str("// from `domains`) stays unconditional: it has no single feature of its\n");
    out.push_str("// own to gate behind, and is compiled in by whichever domain(s) attach\n");
    out.push_str("// it via `uses_framework`.\n");
    for name in all_dirs {
        if domains.iter().any(|d| d == name) {
            out.push_str(&format!("#[cfg(feature = {name:?})]\n"));
        }
        out.push_str(&format!("pub mod {name};\n"));
    }
    out.push('\n');
    out.push_str("// `active` is whichever ONE domain's own merged Store/dispatch table\n");
    out.push_str("// is selected by Cargo feature (rust/Cargo.toml, kept in sync with this\n");
    out.push_str("// list by hecks project_rust) — kernel/cli.rs imports\n");
    out.push_str("// `crate::generated::active::{dispatch_by_name, Store, ...}` unchanged\n");
    out.push_str("// no matter which domain that resolves to.\n");
    out.push_str("//\n");
    out.push_str("// DOMAIN FEATURES ARE MUTUALLY EXCLUSIVE (R5) — Cargo has no native\n");
    out.push_str(&format!("// concept of that, and `default = [{target_mod_name:?}]` in\n"));
    out.push_str("// Cargo.toml stays enabled unless a build passes\n");
    out.push_str("// `--no-default-features`, so a plain `cargo build --features banking`\n");
    out.push_str("// used to enable BOTH the default domain's feature and banking's,\n");
    out.push_str("// producing two `pub use ... as active;` imports and a hard E0252.\n");
    out.push_str("// Fixed two ways below, entirely mechanically from `domains`/\n");
    out.push_str("// `target_mod_name` (this run's new default) — never hand-maintained:\n");
    out.push_str("//\n");
    out.push_str("//   1. THE DEFAULT DOMAIN'S OWN re-export backs off whenever any OTHER\n");
    out.push_str("//      domain feature is also enabled, so it never contends for `active`\n");
    out.push_str("//      by accident — `cargo build --features banking` (still implicitly\n");
    out.push_str("//      carrying the default feature) now resolves to banking alone,\n");
    out.push_str("//      same as if `--no-default-features` had been passed explicitly.\n");
    out.push_str("//   2. Two NON-default domain features enabled TOGETHER (a genuine,\n");
    out.push_str("//      not-accidental conflict — nothing makes that combination\n");
    out.push_str("//      meaningful) still fail the build, but with an explicit\n");
    out.push_str("//      `compile_error!` naming both features instead of a cryptic\n");
    out.push_str("//      \"defined multiple times\".\n");
    for name in domains {
        let other_domains: Vec<&String> = domains.iter().filter(|n| n.as_str() != name.as_str()).collect();
        if name.as_str() == target_mod_name && !other_domains.is_empty() {
            let guard = other_domains.iter().map(|o| format!("feature = {o:?}")).collect::<Vec<_>>().join(", ");
            out.push_str(&format!("#[cfg(all(feature = {name:?}, not(any({guard}))))]\n"));
        } else {
            out.push_str(&format!("#[cfg(feature = {name:?})]\n"));
        }
        out.push_str(&format!("pub use {name}::merged as active;\n"));
    }

    let non_default_domains: Vec<&String> = domains.iter().filter(|n| n.as_str() != target_mod_name).collect();
    if non_default_domains.len() > 1 {
        out.push('\n');
        out.push_str("// Explicit conflict guard — see point 2 above. Only fires when TWO\n");
        out.push_str("// non-default domain features are both turned on; the default\n");
        out.push_str("// domain's own feature never reaches here (point 1 already excludes\n");
        out.push_str("// it whenever any other domain feature is present).\n");
        let domains_joined = domains.join(", ");
        for i in 0..non_default_domains.len() {
            for j in (i + 1)..non_default_domains.len() {
                let a = non_default_domains[i];
                let b = non_default_domains[j];
                out.push_str(&format!("#[cfg(all(feature = {a:?}, feature = {b:?}))]\n"));
                out.push_str(&format!(
                    "compile_error!(\"domain features are mutually exclusive — enable only one of: {domains_joined} (both {a} and {b} are enabled)\");\n"
                ));
            }
        }
    }

    let path = out_root.join("mod.rs");
    std::fs::write(&path, out).map_err(|e| format!("writing {}: {e}", path.display()))?;
    println!("wrote {}", path.display());
    Ok(())
}

/// The `[features]` table text, from its header to the next `[section]` header or EOF.
/// Empty if there is no `[features]` header.
fn features_table_slice(text: &str) -> &str {
    let Some(start) = text.find("[features]") else { return "" };
    let rest = &text[start..];
    let mut pos = 0;
    for (i, line) in rest.split_inclusive('\n').enumerate() {
        if i > 0 && line.trim_start().starts_with('[') {
            return &rest[..pos];
        }
        pos += line.len();
    }
    rest
}

fn sync_cargo_toml_features(cargo_toml_path: &Path, domains: &[String], target_mod_name: &str) -> Result<(), String> {
    let mut cargo_toml = std::fs::read_to_string(cargo_toml_path).map_err(|e| format!("reading {}: {e}", cargo_toml_path.display()))?;

    if !cargo_toml.contains("[features]") {
        let preamble = "# ONE FEATURE PER GENERATED DOMAIN — selects which domain's own\n\
             # generated::<domain>::merged module `generated::active` re-exports\n\
             # (rust/src/generated/mod.rs). Kept in sync by hecks project_rust: a\n\
             # feature is added here whenever a new domain is generated, never\n\
             # removed (the domain's own generated/<name>/ directory is the\n\
             # source of truth for whether it still exists). `default` tracks\n\
             # whichever domain was generated MOST RECENTLY, so a bare\n\
             # `cargo build`/`cargo test` keeps behaving exactly as it always\n\
             # has; any other still-generated domain stays reachable via\n\
             # `--no-default-features --features <name>`.\n\
             [features]\n\
             default = []\n\n";
        cargo_toml = format!("{preamble}{cargo_toml}");
    }

    // Scoped to `[features]`: matching `name = ` file-wide hits `[package]` keys like `version`.
    for name in domains {
        let already_declared = features_table_slice(&cargo_toml).lines().any(|line| {
            line.trim_start().strip_prefix(name.as_str()).map(|rest| rest.trim_start().starts_with('=')).unwrap_or(false)
        });
        if already_declared {
            continue;
        }
        cargo_toml = insert_after_default(&cargo_toml, &format!("{name} = []"));
    }

    cargo_toml = replace_default_line(&cargo_toml, &format!("default = [{:?}]", target_mod_name));

    std::fs::write(cargo_toml_path, &cargo_toml).map_err(|e| format!("writing {}: {e}", cargo_toml_path.display()))?;
    println!("wrote {} (default feature: {target_mod_name})", cargo_toml_path.display());
    Ok(())
}

fn find_default_line_span(text: &str) -> Option<(usize, usize)> {
    let mut pos = 0;
    for line in text.split_inclusive('\n') {
        let content = line.strip_suffix('\n').unwrap_or(line);
        if is_default_line(content) {
            return Some((pos, pos + content.len()));
        }
        pos += line.len();
    }
    None
}

// Always re-finds the original `default` line, so features added in one run land in reverse
// order, matching the Ruby pipeline byte-for-byte.
fn insert_after_default(text: &str, new_line: &str) -> String {
    match find_default_line_span(text) {
        Some((_start, end)) => {
            let mut out = String::with_capacity(text.len() + new_line.len() + 1);
            out.push_str(&text[..end]);
            out.push('\n');
            out.push_str(new_line);
            out.push_str(&text[end..]);
            out
        }
        None => text.to_string(),
    }
}

fn replace_default_line(text: &str, new_line: &str) -> String {
    match find_default_line_span(text) {
        Some((start, end)) => format!("{}{}{}", &text[..start], new_line, &text[end..]),
        None => text.to_string(),
    }
}

fn is_default_line(line_content: &str) -> bool {
    let trimmed = line_content.trim_start();
    trimmed.strip_prefix("default").map(|rest| rest.trim_start().starts_with('=')).unwrap_or(false)
}

/// Rewrites the root `mod.rs` and syncs `rust/Cargo.toml`'s `[features]` for the domains on disk.
pub fn run(out_root: &Path, cargo_toml_path: &Path, target_mod_name: &str) -> Result<(), String> {
    let (all_dirs, domains) = scan_generated_dirs(out_root)?;
    write_root_mod(out_root, &all_dirs, &domains, target_mod_name)?;
    sync_cargo_toml_features(cargo_toml_path, &domains, target_mod_name)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn inserts_after_the_default_line() {
        let text = "[features]\ndefault = []\n\n";
        let result = insert_after_default(text, "pizzas = []");
        assert_eq!(result, "[features]\ndefault = []\npizzas = []\n\n");
    }

    #[test]
    fn later_insertions_land_before_earlier_ones_matching_rubys_quirk() {
        let text = "[features]\ndefault = []\n";
        let after_a = insert_after_default(text, "a = []");
        let after_b = insert_after_default(&after_a, "b = []");
        assert_eq!(after_b, "[features]\ndefault = []\nb = []\na = []\n");
    }

    #[test]
    fn replaces_the_default_line_content() {
        let text = "[features]\ndefault = []\npizzas = []\n";
        let result = replace_default_line(text, "default = [\"banking\"]");
        assert_eq!(result, "[features]\ndefault = [\"banking\"]\npizzas = []\n");
    }
}
