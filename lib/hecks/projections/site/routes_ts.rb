# frozen_string_literal: true

require "json"
require_relative "../../projector"
require_relative "table"

module Hecks
  module Projections
    module Site
      # A site's route table as one dependency-free TypeScript module, `routes.ts`.
      #
      # The module holds the table as `as const` data and the few pure helpers the site's
      # middleware, navigation, sitemap, robots file and content system need over it, so each reads
      # one file instead of carrying its own copy of which pages exist. Nothing in it depends on a
      # framework: it is an ES module that Node (type stripping) and any bundler load as it stands.
      #
      # The text is a pure function of the table: rows keep the order the client declared them in,
      # every list derived from them is sorted by an explicit key, and nothing in it names a time
      # or a machine, so regenerating from the same table changes nothing.
      module RoutesTs
        extend Projector::Target

        projects_as :site_routes_ts, emits: :files

        # The banner every generated file starts with.
        BANNER = "// Generated by hecks project_site. Do not edit."

        # The path of the row that stands for the edge's default behaviour. It matches every path,
        # so it hides none from search.
        CATCH_ALL = "/*"

        # The URL prefix under which a draft preview is served.
        PREVIEW_PREFIX = "/admin-preview"

        module_function

        # Renders `routes.ts` for a route table.
        #
        # @param bluebook [Bluebook::Chapter] the chapter that declares the route table
        # @param options [Hash{Symbol => Object}] `:registry` (Runtime::Registry) the project booted
        #   into, which holds the Site chapter; `:table` (Table) a table already read, instead
        # @return [Hash{String => String}] `"routes.ts"` to its text
        # @raise [Table::Invalid] when the table is refused
        def call(bluebook:, options: {})
          table = options[:table] || Table.read(bluebook, registry: options.fetch(:registry))
          { "routes.ts" => render(table) }
        end

        # @param table [Table] a checked table
        # @return [String] the module's text, ending in a newline
        def render(table)
          rows = table.rows
          [BANNER, header, routes(rows), types, switches(rows), redirects(rows), middleware(rows),
           navigation(table), search(rows), sources(rows), helpers].join("\n\n") << "\n"
        end

        # @param rows [Array<Table::Row>] the table's rows
        # @return [Array<Table::Row>] the rows that exist: those not switched off
        def live(rows) = rows.reject(&:off)

        def header
          <<~TS.chomp
            // The route table of this site, projected from its bluebook's Route rows. Change the rows and run
            // `hecks project_site`; `hecks project_site --check` fails when this file is out of date.
          TS
        end

        def types
          <<~TS.chomp
            export type Route = (typeof ROUTES)[number];
          TS
        end

        def routes(rows)
          lines = rows.map { |row| "  #{literal(route_fields(row))}," }
          "export const ROUTES = [\n#{lines.join("\n")}\n] as const;"
        end

        def route_fields(row)
          { path: row.path, kind: row.kind, render: row.render, auth: row.auth, methods: row.verbs,
            cache: row.cache, origin: row.origin, source: row.source, indexable: row.indexable,
            switch: blank_to_nil(row.switch), off: row.off, preview: row.preview,
            label: blank_to_nil(row.label), seo: blank_to_nil(row.seo), redirectTo: row.redirect_to }
        end

        def switches(rows)
          switched = rows.reject { |row| row.switch.empty? }.group_by(&:switch)
          ids = switched.sort.to_h { |id, group| [id.to_sym, group.none?(&:off)] }
          "// A page's switch: false while the page is off. A page without a switch is always on.\n" \
            "export const SWITCHES: Readonly<Record<string, boolean>> = #{literal(ids)};"
        end

        def redirects(rows)
          pairs = rows.flat_map do |row|
            targeted = row.kind == "redirect" ? [[row.path, row.redirect_to]] : []
            targeted + row.aliases.map { |from| [from, row.path] }
          end
          items = pairs.sort.map { |from, to| "  #{literal({ from: from, to: to, status: 301 })}," }
          "export const REDIRECTS = [\n#{items.join("\n")}\n] as const;".sub("[\n\n]", "[]")
        end

        def middleware(rows)
          off = rows.select(&:off).flat_map { |row| [row.path, *row.aliases] }.sort
          <<~TS.chomp
            // The three rules the site's middleware applies, as data: a switched-off page answers 404, a
            // request under the preview prefix is served from draft content, and `.html` is dropped.
            export const MIDDLEWARE = {
              off: { status: 404, paths: #{literal(off)} },
              preview: { prefix: #{literal(PREVIEW_PREFIX)} },
              stripHtml: { suffix: ".html" },
            } as const;
          TS
        end

        def navigation(table)
          rows = live(table.rows)
          [nav_const("NAV_DESKTOP", "The desktop navigation: a page with no group is its own entry; a group holds its pages.",
                     desktop(rows)),
           nav_const("NAV_MOBILE", "The mobile navigation, in its own order.", mobile(rows)),
           nav_const("NAV_FOOTER", "The footer columns, left to right, each with its links.", footer(rows)),
           nav_const("NAV_ADMIN", "The admin navigation: each admin page under its key.", admin(rows))].join("\n\n")
        end

        def nav_const(name, comment, entries)
          body = entries.map { |entry| "  #{literal(entry)}," }
          "// #{comment}\nexport const #{name} = #{body.empty? ? '[]' : "[\n#{body.join("\n")}\n]"} as const;"
        end

        def desktop(rows)
          items = rows.reject { |row| row.nav_order.nil? }.sort_by { |row| [row.nav_order, row.path] }
          entries = []
          items.each do |row|
            item = { path: row.path, label: row.label }
            group = row.nav_group
            slot = group && entries.find { |entry| entry[:group] == group }
            slot ? slot[:items] << item : entries << { group: group, items: [item] }
          end
          entries
        end

        def mobile(rows)
          rows.reject { |row| row.mobile_order.nil? }.sort_by { |row| [row.mobile_order, row.path] }
              .map { |row| { path: row.path, label: row.label } }
        end

        def footer(rows)
          columns = rows.select(&:footer_column).sort_by { |row| [row.footer_order, row.path] }.group_by(&:footer_column)
          columns.sort_by { |name, group| [group.first.footer_order, name] }
                 .map { |name, group| { column: name, items: group.map { |row| { path: row.path, label: row.label } } } }
        end

        def admin(rows)
          rows.select(&:admin_key).sort_by { |row| [row.admin_order, row.admin_key] }
              .map { |row| { key: row.admin_key, path: row.path, label: row.label } }
        end

        def search(rows)
          sitemap = live(rows).select { |row| row.indexable && !row.path.match?(/[:*]/) }.map(&:path).sort
          hidden = rows.reject { |row| row.indexable || row.path == CATCH_ALL }.flat_map { |row| [row.path, *row.aliases] }.sort
          <<~TS.chomp
            // The paths a sitemap lists: indexable pages with no parameter. A collection's pages are listed
            // from its entries, through `collectionPages`.
            export const SITEMAP_PATHS = #{literal(sitemap)} as const;

            // The routes a search engine is kept away from: every route that is not indexable.
            export const NOT_FOR_SEARCH = #{literal(hidden)} as const;

            // robots.txt `Disallow` prefixes: each non-public route up to its first parameter.
            export const ROBOTS_DISALLOW = #{literal(robots(live(rows)))} as const;
          TS
        end

        def robots(rows)
          prefixes = rows.reject { |row| row.auth == "public" }.map { |row| robots_prefix(row.path) }
          prefixes = (prefixes + ["#{PREVIEW_PREFIX}/"]).uniq.sort
          prefixes.reject { |prefix| prefixes.any? { |other| other != prefix && prefix.start_with?(other) } }
        end

        def robots_prefix(path)
          head = path.split("/").take_while { |part| !part.match?(/\A[:*]/) }.join("/")
          head == path ? path : "#{head}/"
        end

        def sources(rows)
          globals = sourced(rows, "global:", &:path)
          collections = sourced(rows, "collection:") { |row| { path: row.path, indexable: row.indexable } }
          previews = rows.select { |row| row.source.match?(/\A(global|collection):/) }
                         .to_h { |row| [row.source, { path: row.path, draft: row.preview == "draft" }] }.sort.to_h
          <<~TS.chomp
            // A CMS global's slug to the page that shows it.
            export const globalPages = #{literal(globals)} as const;

            // A CMS collection's name to the page that shows one of its entries, and whether the sitemap lists them.
            export const collectionPages = #{literal(collections)} as const;

            const PREVIEWS: Readonly<Record<string, { readonly path: string; readonly draft: boolean }>> = #{literal(previews)};
          TS
        end

        def sourced(rows, prefix)
          rows.select { |row| row.source.start_with?(prefix) }
              .to_h { |row| [row.source.delete_prefix(prefix), yield(row)] }.sort.to_h
        end

        def helpers = [path_helpers, page_helpers].join("\n\n")

        def path_helpers
          <<~'TS'.chomp
            /** Drops a trailing `.html` and a trailing slash, so `/about.html`, `/about/` and `/about` are one path. */
            export function stripHtml(pathname: string): string {
              const bare = pathname.endsWith(".html") ? pathname.slice(0, -".html".length) : pathname;
              return bare.length > 1 && bare.endsWith("/") ? bare.slice(0, -1) : bare;
            }

            function toRegExp(pattern: string): RegExp {
              const source = stripHtml(pattern)
                .split("/")
                .map((part) =>
                  part === "*" ? ".*" : part.startsWith(":") ? "[^/]+" : part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"),
                )
                .join("/");
              return new RegExp("^" + source + "$");
            }

            /** Whether a pathname is one a route pattern (`/blog/:slug.html`, `/pay/*`) describes, with or without `.html`. */
            export function matchesPath(pattern: string, pathname: string): boolean {
              return toRegExp(pattern).test(stripHtml(pathname));
            }
          TS
        end

        def page_helpers
          <<~'TS'.chomp
            /** Whether a page is on: true for an id no row switches off, and for an id no row names. */
            export function pageIsOn(id: string): boolean {
              return Object.prototype.hasOwnProperty.call(SWITCHES, id) ? SWITCHES[id] : true;
            }

            /** Whether a pathname belongs to a switched-off page, with or without `.html`. */
            export function isOffPath(pathname: string): boolean {
              return MIDDLEWARE.off.paths.some((pattern) => matchesPath(pattern, pathname));
            }

            /** Whether a search engine is kept away from a pathname. */
            export function notForSearch(pathname: string): boolean {
              return NOT_FOR_SEARCH.some((pattern) => matchesPath(pattern, pathname));
            }

            /** The URL that previews a CMS source (`global:<slug>` or `collection:<name>`), under the preview prefix when it is a draft. */
            export function previewUrl(source: string, slug?: string): string {
              const entry = PREVIEWS[source];
              if (entry === undefined) throw new Error(`no route has the source ${source}`);
              let path = entry.path;
              if (path.includes(":")) {
                if (slug === undefined) throw new Error(`${source} previews one entry: pass its slug`);
                path = path.replace(/:[A-Za-z_]\w*/, encodeURIComponent(slug));
              }
              return entry.draft ? MIDDLEWARE.preview.prefix + stripHtml(path) : path;
            }
          TS
        end

        def blank_to_nil(text) = text.nil? || text.empty? ? nil : text

        # @param value [Object] a string, number, boolean, nil, array or hash
        # @return [String] the TypeScript literal for it: objects with bare keys, on one line
        def literal(value)
          case value
          when nil then "null"
          when true, false, Integer then value.to_s
          when String then JSON.generate(value)
          when Array then "[#{value.map { |item| literal(item) }.join(', ')}]"
          when Hash then "{ #{value.map { |key, item| "#{key_literal(key)}: #{literal(item)}" }.join(', ')} }".sub("{  }", "{}")
          else raise ArgumentError, "no TypeScript literal for #{value.inspect}"
          end
        end

        def key_literal(key)
          key.to_s.match?(/\A[A-Za-z_$][\w$]*\z/) ? key.to_s : JSON.generate(key.to_s)
        end
      end
    end
  end
end
