# frozen_string_literal: true

require "json"

module Hecks
  module Projections
    module Site
      module SiteHost
        # The text of the two files, written as the file a project would write by hand.
        module Templates
          BANNER = "Generated by hecks site site_projection.project_site. Do not edit."

          module_function

          # @param cms [Hash{Symbol => Object}] the checked `Cms` row
          # @return [String] the image's build file
          def dockerfile(cms)
            format(DOCKERFILE, banner: BANNER, node: cms[:node], port: cms[:port], heap: cms[:heap_mb])
          end

          # @param secrets [Array<Hash{Symbol => Object}>] the checked `BootSecret` rows
          # @return [String] the start-up script
          def boot(secrets)
            ["// #{BANNER}", BOOT_HEAD, *secrets.map { |secret| extra(secret) }, BOOT_TAIL].join("\n\n") << "\n"
          end

          def extra(secret)
            from = JSON.generate(secret[:from])
            env = JSON.generate(secret[:env])
            return field_secret(from, env, JSON.generate(secret[:field])) if secret[:field]

            whole_secret(secret, from, env)
          end

          def field_secret(from, env, field)
            <<~JS.chomp
              if (process.env[#{from}]) {
                process.env[#{env}] = await secretField(process.env[#{from}], #{field});
              }
            JS
          end

          def whole_secret(secret, from, env)
            <<~JS.chomp
              // #{secret[:env]} is the whole of the secret named by #{secret[:from]}. Optional and non-fatal.
              if (process.env[#{from}] && !process.env[#{env}]) {
                try {
                  const { SecretString } = await client.send(new GetSecretValueCommand({ SecretId: process.env[#{from}] }));
                  if (SecretString) process.env[#{env}] = SecretString;
                } catch (err) {
                  console.warn(`boot: could not read #{secret[:from]}: ${err instanceof Error ? err.message : err}`);
                }
              }
            JS
          end

          BOOT_HEAD = <<~JS.chomp
            // Cold-start bootstrap: resolve the secrets, then start Next.
            //
            // The database password and the signing secret are fetched from Secrets Manager here, in the
            // process, and composed into the environment keys payload.config.ts reads (DATABASE_URL,
            // PAYLOAD_SECRET), so neither is ever a plaintext environment variable of the task. A
            // DATABASE_URL / PAYLOAD_SECRET already in the environment is used when the *_ARN variables are
            // absent: a person running this file locally.
            import { SecretsManagerClient, GetSecretValueCommand } from "@aws-sdk/client-secrets-manager";

            const client = new SecretsManagerClient({});

            async function secretField(arn, field) {
              const { SecretString } = await client.send(new GetSecretValueCommand({ SecretId: arn }));
              const value = JSON.parse(SecretString)[field];
              if (!value) throw new Error(`secret ${arn} has no "${field}" field`);
              return value;
            }

            if (process.env.DB_SECRET_ARN) {
              const { DB_HOST, DB_NAME } = process.env;
              if (!DB_HOST || !DB_NAME) throw new Error("DB_HOST and DB_NAME are required when DB_SECRET_ARN is set");
              const password = await secretField(process.env.DB_SECRET_ARN, "password");
              // The password goes through encodeURIComponent: the generated one can hold characters (@ / #)
              // that would otherwise split the URL. RDS enforces TLS; verify against Amazon's CA bundle,
              // which the image holds beside this file.
              const ssl = "sslmode=verify-full&sslrootcert=" + new URL("./rds-global-bundle.pem", import.meta.url).pathname;
              process.env.DATABASE_URL = `postgres://postgres:${encodeURIComponent(password)}@${DB_HOST}:5432/${DB_NAME}?${ssl}`;
            } else if (!process.env.DATABASE_URL) {
              throw new Error("either DB_SECRET_ARN (+ DB_HOST/DB_NAME) or DATABASE_URL is required");
            }

            if (process.env.PAYLOAD_SECRET_ARN) {
              process.env.PAYLOAD_SECRET = await secretField(process.env.PAYLOAD_SECRET_ARN, "secret");
            } else if (!process.env.PAYLOAD_SECRET) {
              throw new Error("either PAYLOAD_SECRET_ARN or PAYLOAD_SECRET is required");
            }
          JS

          BOOT_TAIL = <<~JS.chomp
            // Next's standalone server starts listening on import (PORT and HOSTNAME come from the environment).
            await import("./server.js");
          JS

          DOCKERFILE = <<~'DOCKER'
            # %<banner>s
            #
            # The content system (Payload on Next's standalone server) as a container. Build from this
            # directory. deploy-aws/boot.mjs resolves the secrets named by the *_ARN variables into
            # DATABASE_URL and PAYLOAD_SECRET before it starts the server, so nothing here is a secret.
            #
            # Runtime environment, supplied by the task definition:
            #   NODE_ENV=production, USE_POSTGRES=true, USE_S3_STORAGE=true, S3_MEDIA_BUCKET
            #   DB_HOST, DB_NAME, DB_SECRET_ARN, PAYLOAD_SECRET_ARN, CORS_ORIGINS, AWS_REGION

            # ---- build stage ----
            FROM node:%<node>s-slim AS build
            WORKDIR /app

            # A lockfile written on macOS omits the Linux entries of optional native packages
            # (sharp), and `next build` then fails deep inside page-data collection. Write it on the
            # image's own platform: remove node_modules and package-lock.json and run npm install.
            COPY package.json package-lock.json ./
            RUN npm ci

            COPY . .
            # payload-types.ts is generated and untracked, so a clean checkout has none and the type check
            # inside `next build` would see untyped results. Generating it only loads the config
            # (no database); the values are placeholders and the flags are the ones production boots with.
            RUN USE_POSTGRES=true USE_S3_STORAGE=true PAYLOAD_SECRET=build-only \
                S3_MEDIA_BUCKET=build-only AWS_REGION=us-east-1 DATABASE_URL=postgres://build-only/build-only \
                npm run generate:types
            RUN npm run build

            # ---- runtime stage ----
            FROM node:%<node>s-slim
            WORKDIR /app
            ENV NODE_ENV=production
            # The task is shared with sibling containers; without a cap Node sizes its heap from the whole task.
            ENV NODE_OPTIONS=--max-old-space-size=%<heap>d

            # Next's standalone output holds a minimal server.js and its traced node_modules; the static
            # files are not part of it and are copied separately.
            COPY --from=build /app/.next/standalone/ ./
            COPY --from=build /app/.next/static ./.next/static

            COPY deploy-aws/boot.mjs ./
            # RDS enforces TLS; boot.mjs verifies against Amazon's CA bundle.
            ADD https://truststore.pki.rds.amazonaws.com/global/global-bundle.pem ./rds-global-bundle.pem

            # boot.mjs sits outside the Next app, so `next build` does not trace its import of the AWS SDK.
            COPY --from=build /app/node_modules/@aws-sdk ./node_modules/@aws-sdk
            COPY --from=build /app/node_modules/@smithy ./node_modules/@smithy
            COPY --from=build /app/node_modules/tslib ./node_modules/tslib

            # Next's standalone server reads HOSTNAME for its bind address.
            ENV HOSTNAME=0.0.0.0
            ENV PORT=%<port>d
            EXPOSE %<port>d

            # Nothing writes to /app at runtime (media goes to S3), so no root.
            USER node
            CMD ["node", "boot.mjs"]
          DOCKER
        end
      end
    end
  end
end
