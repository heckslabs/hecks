# frozen_string_literal: true

require "json"
require_relative "specs/wire"

module Hecks
  module Projections
    module Site
      module Payload
        # The TypeScript the content system drives each aggregate with: its input type, how an input
        # goes over the wire, how the host's state reads back into one, and the lifecycle the domain
        # allows. The decisions that turn these into commands are in the lifecycle module, which the
        # specs only describe.
        module Specs
          BANNER = "// Generated by hecks site site_projection.project_site. Do not edit."

          module_function

          # @param aggregates [Array<Model::Aggregate>] the aggregates to drive
          # @param lifecycle [String] the import path of the lifecycle module
          # @param hecks [String] the import path of the module that talks to the host
          # @return [String] the module
          def render(aggregates, lifecycle:, hecks:)
            body = aggregates.map { |agg| aggregate(agg) }.join("\n\n")
            [BANNER, header(aggregates, lifecycle, hecks), helpers(aggregates), body].reject(&:empty?).join("\n\n") << "\n"
          end

          def header(aggregates, lifecycle, hecks)
            imports = %w[instancesOf] + (uses?(aggregates, :integer) ? %w[whole] : [])
            names = %w[optionalValue statusOf unwrap unwrapList wrapped] + %w[type\ Instance type\ Spec type\ Wire]
            <<~TS.chomp
              import { #{imports.join(", ")} } from #{hecks.to_json};
              import { #{names.join(", ")} } from #{lifecycle.to_json};
            TS
          end

          def helpers(aggregates)
            <<~TS.chomp
              const list = (items: string[]) => items.map(wrapped);
              const orNull = (value: unknown) => unwrap(value);#{composite_reader(aggregates)}
            TS
          end

          def composite_reader(aggregates)
            return "" unless uses?(aggregates, :composite)

            <<~TS.chomp.prepend("\n")
              const text = (value: unknown) => (typeof value === "string" ? value : "");
            TS
          end

          def uses?(aggregates, shape) = aggregates.any? { |agg| agg.attrs.any? { |attr| attr.shape == shape } }

          def aggregate(agg)
            [heading(agg), composites(agg), input_type(agg), state_type(agg), composite_readers(agg), spec(agg)]
              .reject(&:empty?).join("\n\n")
          end

          def heading(agg) = "// ---- #{agg.noun} ----"

          def composites(agg)
            agg.attrs.select { |attr| attr.shape == :composite }.map do |attr|
              fields = attr.parts.map { |part| "  #{part.ts}: string;" }.join("\n")
              "export interface #{attr.type} {\n#{fields}\n}"
            end.join("\n\n")
          end

          def input_type(agg)
            fields = agg.attrs.map { |attr| "  #{attr.ts}: #{ts_type(attr)};" }.join("\n")
            "export interface #{agg.noun}Input {\n#{fields}\n}"
          end

          def state_type(agg) = "export type #{agg.noun}State = #{agg.noun}Input & Instance;"

          def ts_type(attr)
            base = if attr.shape == :integer
                     "number"
                   else
                     (attr.shape == :composite ? attr.type : "string")
                   end
            return "#{base}[]" if attr.list

            attr.optional ? "#{base} | null" : base
          end

          def composite_readers(agg)
            agg.attrs.select { |attr| attr.shape == :composite }.map do |attr|
              parts = attr.parts.map { |part| "#{part.ts}: text(s.#{part.name})" }.join(", ")
              <<~TS.chomp
                const #{reader(agg, attr)} = (value: unknown): #{attr.type}[] =>
                  Array.isArray(value) ? value.map((raw) => { const s = (raw ?? {}) as Record<string, unknown>; return { #{parts} }; }) : [];
              TS
            end.join("\n\n")
          end

          def reader(agg, attr) = "#{agg.noun[0].downcase}#{agg.noun[1..]}#{attr.ts[0].upcase}#{attr.ts[1..]}From"

          # The three lines between a spec's reads and its writes.
          SPEC_MIDDLE = ["    })),",
                         "  toInput: ({ status: _status, ...input }) => input,",
                         "  fields: (input): Wire => ({"].freeze

          def spec(agg)
            [*spec_head(agg), Wire.reads(agg), *SPEC_MIDDLE, Wire.writes(agg), *spec_tail(agg)].join("\n")
          end

          def spec_head(agg)
            var = "#{agg.noun[0].downcase}#{agg.noun[1..]}"
            ["export const #{var}Spec: Spec<#{agg.noun}State, #{agg.noun}Input> = {",
             "  aggregate: #{agg.fqn.to_json},",
             "  read: (answer) =>",
             "    instancesOf(answer, #{agg.fqn.to_json}).map(([#{agg.identity}, s]) => ({",
             "      #{agg.identity},",
             "      status: statusOf(s),"]
          end

          def spec_tail(agg)
            ["  }),",
             "  create: { verb: #{agg.create[:verb].to_json}, status: #{agg.create[:status].to_json} },",
             "  edges: #{edges(agg.edges)},",
             "};"]
          end

          def edges(edges)
            rows = edges.map do |status, moves|
              inner = moves.map { |verb, target| "#{verb}: #{target.to_json}" }.join(", ")
              "    #{status}: { #{inner} },"
            end
            "{\n#{rows.join("\n")}\n  }"
          end
        end
      end
    end
  end
end
