# frozen_string_literal: true

require "json"

module Hecks
  module Projections
    module Site
      module Payload
        # The TypeScript that ties a Payload collection to an aggregate: the collection's field
        # definitions, one per attribute, and the function that reads a saved document back into the
        # aggregate's input.
        #
        # Both come from the attribute's shape and, where the editor needs something the shape
        # cannot
        # say (a date picker, a choice list, an upload, a relation), from a `PayloadField` row.
        # They are
        # produced together so a field and the code that reads it cannot disagree.
        module Fields
          BANNER = "// Generated by hecks site site_projection.project_site. Do not edit."

          # The kinds a row may name, with the Payload field type each is.
          KINDS = { "text" => "text", "textarea" => "textarea", "select" => "select", "date" => "date", "day" => "date",
                    "number" => "number", "upload" => "upload", "relationship" => "relationship" }.freeze

          module_function

          # @param aggregates [Array<Model::Aggregate>] the aggregates to drive
          # @param rows [Array<Hash{Symbol => Object}>] the checked `PayloadField` rows
          # @param specs [String] the import path of the generated specs module
          # @param helpers [String] the import path of the module that holds `nonBlank` and its kin
          # @return [String] the module
          # @raise [ArgumentError] when a row names an aggregate or an attribute the domain lacks
          def render(aggregates, rows:, specs:, helpers:)
            check(aggregates, rows)
            body = aggregates.map { |agg| aggregate(agg, rows.select { |row| row[:aggregate] == agg.noun }) }
            [BANNER, header(aggregates, specs, helpers), shared, *body].join("\n\n") << "\n"
          end

          def check(aggregates, rows)
            rows.each do |row|
              agg = aggregates.find { |candidate| candidate.noun == row[:aggregate] }
              raise ArgumentError, "PayloadField names #{row[:aggregate]}, which it does not drive" unless agg

              check_attribute(agg, row)
              check_kind(row)
            end
          end

          def check_attribute(agg, row)
            top, part = row[:attribute].split(".", 2)
            attr = agg.attrs.find { |candidate| candidate.name == top }
            where = "PayloadField #{row[:aggregate]}.#{row[:attribute]}"
            raise ArgumentError, "#{where} is not an attribute" unless attr
            raise ArgumentError, "#{where} is not a part" if part && !attr.parts&.any? { |each| each.name == part }
          end

          def check_kind(row)
            kind = row[:kind]
            if kind && !KINDS.key?(kind)
              raise ArgumentError,
                    "PayloadField kind #{kind.inspect} is one of #{KINDS.keys.join(", ")}"
            end
            return unless %w[upload relationship].include?(kind) && !row[:relation]

            raise ArgumentError, "PayloadField #{row[:attribute]} is #{kind} and needs a relation"
          end

          def header(aggregates, specs, helpers)
            types = aggregates.map { |agg| "type #{agg.noun}Input" }.join(", ")
            <<~TS.chomp
              import type { Field, PayloadRequest } from "payload";

              import { isoOrNull, nonBlank, related, type Doc } from #{helpers.to_json};
              import { #{types} } from #{specs.to_json};
            TS
          end

          def shared
            <<~TS.chomp
              const valuesOf = (value: unknown, pick: (raw: unknown) => string | null): string[] =>
                (Array.isArray(value) ? value : []).map((row) => pick((row as Doc)?.value)).filter((item): item is string => !!item);
            TS
          end

          def aggregate(agg, rows)
            var = "#{agg.noun[0].downcase}#{agg.noun[1..]}"
            fields = fields_of(agg, rows).map { |name, text| "  #{name}: #{text}," }.join("\n")
            inputs = agg.attrs.map { |attr| "  #{attr.ts}: #{input(attr, row_for(rows, attr.name), rows)}," }.join("\n")
            <<~TS.chomp
              // ---- #{agg.noun} ----

              export const #{var}Fields = {
              #{fields}
              } satisfies Record<string, Field>;

              export const #{var}FromDoc = async (req: PayloadRequest, doc: Doc): Promise<#{agg.noun}Input> => ({
              #{inputs}
              });
            TS
          end

          def row_for(rows, attribute, part = nil)
            wanted = part ? "#{attribute}.#{part}" : attribute
            rows.find { |row| row[:attribute] == wanted } || {}
          end

          def fields_of(agg, rows)
            agg.attrs.map do |attr|
              row = row_for(rows, attr.name)
              [field_name(attr, row), field(agg, attr, row, rows)]
            end
          end

          def field_name(attr, row) = row[:field] || attr.ts

          def field(_agg, attr, row, rows)
            name = field_name(attr, row)
            return composite(attr, row, name, rows) if attr.shape == :composite
            return array(attr, row, name) if attr.list

            literal(base(attr, row, name, !attr.optional))
          end

          def kind_of(attr, row)
            row[:kind] || (attr.shape == :integer ? "number" : "text")
          end

          def base(attr, row, name, required)
            kind = kind_of(attr, row)
            required = row[:required] if row.key?(:required)
            pairs = [["name", name.to_json], ["type", KINDS.fetch(kind).to_json]]
            pairs << ["required", "true"] if required
            pairs << ["unique", "true"] if attr.name == "slug"
            pairs << ["defaultValue", row[:default].to_json] if row[:default]
            pairs.concat(extras(kind, row))
          end

          def extras(kind, row, describe: true)
            pairs = []
            pairs << ["options", options(row[:options])] if kind == "select" && row[:options]
            pairs << ["relationTo", row[:relation].to_json] if row[:relation]
            admin = []
            admin << ["description", row[:description].to_json] if describe && row[:description]
            if KINDS[kind] == "date"
              admin << ["date",
                        "{ pickerAppearance: #{(kind == "day" ? "dayOnly" : "dayAndTime").to_json} }"]
            end
            pairs << ["admin", "{ #{admin.map { |key, value| "#{key}: #{value}" }.join(", ")} }"] if admin.any?
            pairs
          end

          def options(text)
            items = text.split(",").map(&:strip).reject(&:empty?).map do |item|
              value, label = item.split("=", 2)
              label ? "{ label: #{label.to_json}, value: #{value.to_json} }" : value.to_json
            end
            "[#{items.join(", ")}]"
          end

          def literal(pairs) = "{ #{pairs.map { |key, value| "#{key}: #{value}" }.join(", ")} }"

          def array(_attr, row, name)
            kind = row[:kind] || "text"
            element = literal([["name", '"value"'], ["type", KINDS.fetch(kind).to_json], ["required", "true"],
                               *extras(kind, row, describe: false)])
            pairs = [["name", name.to_json], ["type", '"array"']]
            pairs << ["labels", labels(row[:label])] if row[:label]
            pairs << ["admin", "{ description: #{row[:description].to_json} }"] if row[:description]
            pairs << ["fields", "[#{element}]"]
            literal(pairs)
          end

          def labels(text)
            singular, plural = text.split("|", 2)
            "{ singular: #{singular.to_json}, plural: #{(plural || "#{singular}s").to_json} }"
          end

          def composite(attr, row, name, rows)
            subs = attr.parts.map do |part|
              part_row = row_for(rows, attr.name, part.name)
              literal(base(part, part_row.merge(required: part_row.fetch(:required, true)), part.ts, true))
            end
            pairs = [["name", name.to_json], ["type", '"array"']]
            pairs << ["labels", labels(row[:label])] if row[:label]
            pairs << ["admin", "{ description: #{row[:description].to_json} }"] if row[:description]
            pairs << ["fields", "[#{subs.join(", ")}]"]
            literal(pairs)
          end

          def input(attr, row, rows)
            return composite_input(attr, rows) if attr.shape == :composite

            name = row[:field] || attr.ts
            kind = kind_of(attr, row)
            return list_input(name, kind) if attr.list

            scalar_input(attr, row, name, kind)
          end

          def list_input(name, kind) = "valuesOf(doc.#{name}, #{kind == "date" ? "isoOrNull" : "nonBlank"})"

          def scalar_input(attr, row, name, kind)
            case kind
            when "upload", "relationship"
              via = row[:via] || (kind == "upload" ? "url" : "slug")
              "await related(req, #{row[:relation].to_json}, doc.#{name}, #{via.to_json})"
            when "date", "day" then date_input(attr, name, kind)
            when "number" then attr.optional ? "doc.#{name} == null ? null : Number(doc.#{name})" : "Number(doc.#{name})"
            else attr.optional ? "nonBlank(doc.#{name})" : "String(doc.#{name})"
            end
          end

          def date_input(attr, name, kind)
            return "isoOrNull(doc.#{name})#{' ?? ""' unless attr.optional}" unless attr.shape == :integer || kind == "day"

            stamp = "doc.#{name} ? new Date(doc.#{name} as string).getTime() : Date.now()"
            "Math.floor((#{stamp}) / 1000)"
          end

          def composite_input(attr, rows)
            parts = attr.parts.map { |part| "#{part.ts}: #{part_input(part, row_for(rows, attr.name, part.name))}" }.join(", ")
            "(Array.isArray(doc.#{attr.ts}) ? doc.#{attr.ts} : []).map((raw) => { const s = raw as Doc; return { #{parts} }; })"
          end

          def part_input(part, row)
            return "isoOrNull(s.#{part.ts}) ?? \"\"" if KINDS[row[:kind]] == "date"

            "nonBlank(s.#{part.ts}) ?? \"\""
          end
        end
      end
    end
  end
end
