# frozen_string_literal: true

require "json"
require_relative "lifecycle/text"
require_relative "lifecycle/text_tail"

module Hecks
  module Projections
    module Site
      module Payload
        # The module that turns a spec and a saved document into the commands between the host's
        # state and the wanted one. It is the same for every project but for the role its commands
        # declare and the path of the module that talks to the host.
        module Lifecycle
          BANNER = "// Generated by hecks site site_projection.project_site. Do not edit."

          # The whole module, with `__ROLE__` and `__HECKS__` standing for the role and the path of
          # the module that talks to the host.
          TEXT = (HEAD + TAIL).freeze

          module_function

          # @param role [String, nil] the role every driven command declares
          # @param hecks [String] the import path of the module that talks to the host
          # @return [String] the module
          def render(role:, hecks:)
            [BANNER, TEXT.sub("__ROLE__", role.to_json).sub("__HECKS__", hecks.to_json)].join("\n\n")
          end
        end
      end
    end
  end
end
