# frozen_string_literal: true

require "json"

module Hecks
  module Projections
    module Site
      module Payload
        # The module that turns a spec and a saved document into the commands between the host's
        # state and
        # the wanted one. It is the same for every project but for the role its commands declare
        # and the
        # path of the module that talks to the host.
        module Lifecycle
          BANNER = "// Generated by hecks site site_projection.project_site. Do not edit."

          module_function

          # @param role [String, nil] the role every driven command declares
          # @param hecks [String] the import path of the module that talks to the host
          # @return [String] the module
          def render(role:, hecks:)
            [BANNER, TEXT.sub("__ROLE__", role.to_json).sub("__HECKS__", hecks.to_json)].join("\n\n")
          end

          TEXT = <<~TS
            // Driving one aggregate from a save: what every driven collection shares.
            //
            // An editor's save says what the document should look like and where it should
            // be (live, withdrawn, cancelled). The domain answers with where the aggregate
            // is now. This works out the commands between the two: create it if the domain
            // has never seen it, Revise when its facts differ, then walk its lifecycle to
            // the wanted status along the shortest path the bluebook allows.
            //
            // The pure parts (the plan) are separate from `drive`, the one function that
            // talks to the domain, so the decisions test without a network.
            import { domain, instancesOf, refusalOf, type Answer } from __HECKS__;

            /** The role every driven command declares; the host compares the role as a plain string. */
            const ROLE = __ROLE__;

            export type Wire = Record<string, unknown>;

            export interface Command<S> {
              verb: string;
              to?: string;
              with: Wire;
              /** True when the instances that came back show the command took effect. */
              confirm: (after: S[]) => boolean;
            }

            export interface Instance {
              slug: string;
              status: string;
            }

            export interface Spec<S extends Instance, I extends { slug: string }> {
              /** The aggregate as the host names it, chapter first: "Club::Event". */
              aggregate: string;
              /** Its instances in an answer, keyed by slug. */
              read: (answer: Answer) => S[];
              /** What the host holds, in the shape a save produces, so the two compare. */
              toInput: (state: S) => Omit<I, "status">;
              /** Every attribute but the slug, as `Revise` takes it. */
              fields: (input: Omit<I, "status">) => Wire;
              /** The command that creates one (it takes the slug and the fields) and the status it leaves it in. */
              create: { verb: string; status: string };
              /** The lifecycle: from a status, the commands that leave it and where they lead. */
              edges: Record<string, Record<string, string>>;
            }

            /** A refusal-free plan: nothing is sent for a status the domain cannot reach from where it is. */
            export class UnreachableStatus extends Error {}

            export const wrapped = (value: string) => ({ value });
            export const optionalValue = (name: string, value: string | null | undefined) => (value ? { [name]: wrapped(value) } : {});

            /** The text inside a one-attribute value object (`{value}`, `{url}`, `{address}`), or null. */
            export function unwrap(value: unknown): string | null {
              if (typeof value === "string") return value || null;
              if (value && typeof value === "object") {
                for (const key of ["value", "url", "address"]) {
                  const inner = (value as Record<string, unknown>)[key];
                  if (typeof inner === "string" && inner) return inner;
                }
              }
              return null;
            }

            export const unwrapList = (value: unknown): string[] =>
              Array.isArray(value) ? value.map(unwrap).filter((item): item is string => !!item) : [];

            export const statusOf = (state: Record<string, unknown>): string => (typeof state.status === "string" ? state.status : "");

            /** The verbs, in order, that take an aggregate from one status to another; null when none does. */
            export function pathBetween(edges: Record<string, Record<string, string>>, from: string, to: string): string[] | null {
              if (from === to) return [];
              const seen = new Set([from]);
              let frontier: { status: string; verbs: string[] }[] = [{ status: from, verbs: [] }];
              while (frontier.length) {
                const next: typeof frontier = [];
                for (const { status, verbs } of frontier) {
                  for (const [verb, target] of Object.entries(edges[status] ?? {})) {
                    if (seen.has(target)) continue;
                    if (target === to) return [...verbs, verb];
                    seen.add(target);
                    next.push({ status: target, verbs: [...verbs, verb] });
                  }
                }
                frontier = next;
              }
              return null;
            }

            const stateOf = <S extends Instance>(after: S[], slug: string) => after.find((s) => s.slug === slug);

            /**
             * The commands that make the domain's aggregate match `input` and sit in
             * `desired`. `desired` null means "not on the site": a document the domain has
             * never seen sends nothing; one it holds is walked to `withdrawn`.
             */
            export function planCommands<S extends Instance, I extends { slug: string }>(
              spec: Spec<S, I>,
              current: S | undefined,
              input: Omit<I, "status">,
              desired: string,
            ): Command<S>[] {
              const slug = input.slug;
              const fields = spec.fields(input);
              const commands: Command<S>[] = [];
              let status = current?.status;

              if (!current) {
                if (spec.create.status !== desired && !pathBetween(spec.edges, spec.create.status, desired)) {
                  throw new UnreachableStatus(`${spec.aggregate} cannot reach "${desired}" from "${spec.create.status}".`);
                }
                commands.push({
                  verb: spec.create.verb,
                  with: { slug: wrapped(slug), ...fields },
                  confirm: (after) => stateOf(after, slug)?.status === spec.create.status,
                });
                status = spec.create.status;
              } else if (JSON.stringify(spec.fields(spec.toInput(current))) !== JSON.stringify(fields)) {
                commands.push({
                  verb: "Revise",
                  to: slug,
                  with: fields,
                  confirm: (after) => {
                    const now = stateOf(after, slug);
                    return !!now && JSON.stringify(spec.fields(spec.toInput(now))) === JSON.stringify(fields);
                  },
                });
              }

              const path = pathBetween(spec.edges, status ?? "", desired);
              if (path === null) throw new UnreachableStatus(`${spec.aggregate} "${slug}" cannot go from "${status}" to "${desired}".`);
              let at = status ?? "";
              for (const verb of path) {
                const to = spec.edges[at][verb];
                commands.push({ verb, to: slug, with: {}, confirm: (after) => stateOf(after, slug)?.status === to });
                at = to;
              }
              return commands;
            }

            /** Runs the plan against the domain; a command whose result does not show it took effect throws the domain's own words. */
            export async function drive<S extends Instance, I extends { slug: string }>(
              spec: Spec<S, I>,
              input: Omit<I, "status">,
              desired: string | null,
              /** The status that means "off the site", used when `desired` is null and the domain holds the aggregate. */
              offSite: string,
            ): Promise<void> {
              const current = spec.read(await domain().read()).find((s) => s.slug === input.slug);
              // Not on the site and never was (a draft): the domain hears nothing about it.
              if (desired === null && !current) return;
              for (const command of planCommands(spec, current, input, desired ?? offSite)) {
                const verb = `${spec.aggregate.split("::")[1]}.${command.verb}`;
                const answer = await domain().dispatch(verb, command.with, command.to, ROLE);
                if (!command.confirm(spec.read(answer))) throw refusalOf(answer, verb);
              }
            }

            /** Reads an aggregate's instances, slug first, from an answer. */
            export const instancesBySlug = (answer: Answer, aggregate: string) => instancesOf(answer, aggregate);
          TS
        end
      end
    end
  end
end
