module Hecks
  module Projections
    module Diagrams
      # The index over one domain's diagrams: a Markdown list that GitHub renders, grouped by
      # kind, with each diagram's subject from its own header. `IndexPage` draws the same
      # list as one HTML page.
      module Index
        module_function

        # The order the sections are listed in; a section not named here comes last.
        SECTION_ORDER = ["Overview", "Whole domain", "Lifecycles", "Process managers", "Surfaces"].freeze

        SUFFIX_SECTIONS = {
          "_lifecycle.mmd" => "Lifecycles",
          "_saga.mmd" => "Process managers",
          "_surface.mmd" => "Surfaces"
        }.freeze

        # @param generated [Hash{String => String}] every diagram this run wrote, by filename
        # @param bluebook [Bluebook::Declaration] the bluebook the diagrams came from
        # @return [Hash{String => String}] `README.md` and `index.html`, by filename
        def files(generated, bluebook)
          { "README.md" => markdown(generated, bluebook), "index.html" => IndexPage.html(generated, bluebook) }
        end

        # Diagram filenames in the order the index lists them: by section, then by name.
        def ordered(generated)
          generated.keys.sort_by { |name| [SECTION_ORDER.index(section_of(name)) || SECTION_ORDER.size, name] }
        end

        def section_of(name)
          return "Overview" if name == "overview.mmd"

          SUFFIX_SECTIONS.find { |suffix, _| name.end_with?(suffix) }&.last || "Whole domain"
        end

        # The subject from a diagram's header, the part a reader needs to know what it draws.
        def subject(source)
          source.to_s.lines.first.to_s[/ from (.+?) — DO NOT EDIT/, 1].to_s
        end

        # @return [String] the Markdown index
        def markdown(generated, bluebook)
          sections = ordered(generated).group_by { |name| section_of(name) }
          body = sections.map { |section, names| section_markdown(section, names, generated) }
          "<!-- GENERATED by hecks project_diagrams from #{bluebook.name} — DO NOT EDIT BY HAND. -->\n" \
            "# #{bluebook.name} diagrams\n\n#{body.join("\n")}"
        end

        def section_markdown(section, names, generated)
          items = names.map { |name| "- [#{name}](#{name}) — #{subject(generated[name])}" }
          "## #{section}\n\n#{items.join("\n")}\n"
        end
      end
    end
  end
end
