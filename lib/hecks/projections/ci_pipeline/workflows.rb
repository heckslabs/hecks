# frozen_string_literal: true

require_relative "../../projector"
require_relative "table"
require_relative "yaml_text"

module Hecks
  module Projections
    module CiPipeline
      # A client's workflow rows as GitHub Actions workflow files, one per `Workflow` row.
      #
      # The text is a pure function of the rows: workflows, jobs and steps keep the order the client
      # declared them in, and nothing in it names a time or a machine, so regenerating from the same
      # rows changes nothing. A modeled `note` is written as the comment above what it belongs to.
      module Workflows
        extend Projector::Target

        projects_as :ci_workflows, emits: :files

        # Where the files go, relative to the checkout.
        DIRECTORY = ".github/workflows"

        # The banner every generated file starts with.
        BANNER = "# Generated by hecks regeneration_run.project_ci_pipeline. Do not edit; change the workflow rows."

        # What each event of the chapter's `Trigger` set is written as under `on:`.
        EVENTS = { "push_main" => ["push:", "  branches: [main]"], "pull_request" => ["pull_request:"],
                   "workflow_dispatch" => ["workflow_dispatch:"] }.freeze

        module_function

        # Renders each workflow of a table of rows.
        #
        # @param bluebook [Bluebook::Chapter] the bluebook that declares the rows
        # @param options [Hash{Symbol => Object}] `:registry` (Runtime::Registry) the project booted
        #   into, which holds the CiPipeline bluebook; `:table` (Table) a table already read
        # @return [Hash{String => String}] each file's path under the checkout to its text
        # @raise [Table::Invalid] when the rows are refused
        def call(bluebook:, options: {})
          table = options[:table] || Table.read(bluebook, registry: options.fetch(:registry))
          table.workflows.to_h { |workflow| ["#{DIRECTORY}/#{workflow.name}", render(workflow)] }
        end

        # @param workflow [Table::Rows::Workflow] a checked workflow
        # @return [String] the file's text, ending in a newline
        def render(workflow)
          sections = [[BANNER], ["name: #{YamlText.scalar(workflow.display_name)}"], note(workflow.note),
                      triggers(workflow), concurrency(workflow), jobs(workflow)]
          "#{sections.reject(&:empty?).map { |lines| lines.join("\n") }.join("\n\n")}\n"
        end

        def note(text) = text.empty? ? [] : YamlText.comment(text)

        def triggers(workflow)
          ["on:", *YamlText.indent(workflow.triggers.flat_map { |event| event_lines(event, workflow) }, 2)]
        end

        def event_lines(event, workflow)
          return EVENTS.fetch(event) unless event == "workflow_call"

          ["workflow_call:", *YamlText.indent(secrets(workflow), 2)]
        end

        def secrets(workflow)
          return [] if workflow.secrets.empty?

          ["secrets:", *YamlText.indent(workflow.secrets.flat_map { |secret| secret_lines(secret) }, 2)]
        end

        def secret_lines(secret)
          ["#{YamlText.key(secret.name)}:", "  required: #{secret.required}"]
        end

        def concurrency(workflow)
          return [] if workflow.concurrency_group.empty?

          ["concurrency:", "  group: #{YamlText.scalar(workflow.concurrency_group)}",
           "  cancel-in-progress: #{workflow.cancel_in_progress}"]
        end

        def jobs(workflow)
          blocks = workflow.jobs.map { |job| YamlText.indent([*note(job.note), *job_lines(job)], 2) }
          ["jobs:", *blocks.flat_map { |lines| [*lines, ""] }[0...-1]]
        end

        def job_lines(job)
          body = [*headline(job), *needs(job), *condition(job), *strategy(job), *pairs("outputs", job.outputs),
                  *pairs("env", job.env), *steps(job)]
          ["#{YamlText.key(job.name)}:", *YamlText.indent(body, 2)]
        end

        def headline(job)
          ["runs-on: #{YamlText.scalar(job.runner)}", "timeout-minutes: #{job.timeout_minutes}", *permissions(job)]
        end

        def permissions(job)
          return [] if job.permissions.empty?

          ["permissions:", *job.permissions.split(", ").map { |scope| "  #{scope}" }]
        end

        def needs(job)
          return [] if job.needs.empty?
          return ["needs: #{YamlText.scalar(job.needs.first)}"] if job.needs.one?

          ["needs: [#{job.needs.map { |name| YamlText.scalar(name) }.join(", ")}]"]
        end

        def condition(job) = job.condition.empty? ? [] : YamlText.folded("if", job.condition)

        # A sharded job runs one leg for each number up to its total, and no leg cancels another.
        def strategy(job)
          return [] unless job.shard_total > 1

          ["strategy:", "  fail-fast: false", "  matrix:",
           "    #{YamlText.key(job.shard_axis)}: [#{(1..job.shard_total).to_a.join(", ")}]"]
        end

        def pairs(key, entries)
          return [] if entries.empty?

          ["#{key}:", *entries.map { |pair| "  #{YamlText.key(pair.key)}: #{YamlText.scalar(pair.value)}" }]
        end

        def steps(job)
          lines = job.steps.each_with_index.flat_map do |step, index|
            separator = index.positive? && !step.note.empty? ? [""] : []
            [*separator, *note(step.note), *step_lines(step, job)]
          end
          ["steps:", *YamlText.indent(lines, 2)]
        end

        def step_lines(step, job)
          fields = [*scalar_field("name", step.title), *scalar_field("id", step.id), *condition_of(step),
                    *scalar_field("uses", step.uses), *pairs("with", step.inputs), *command(step, job)]
          fields.each_with_index.map { |line, index| index.zero? ? "- #{line}" : "  #{line}" }
        end

        def scalar_field(key, text) = text.empty? ? [] : ["#{key}: #{YamlText.scalar(text)}"]

        def condition_of(step) = step.condition.empty? ? [] : YamlText.folded("if", step.condition)

        def command(step, job)
          return [] if step.run.empty?

          YamlText.literal("run", step.run.gsub(Table::Checks::SHARD_TOKEN, job.shard_total.to_s))
        end
      end
    end
  end
end
