require_relative "../projector"
require_relative "parser_table"

module Hecks
  module Projections
    # The Rust parser's sentence table, projected from the Sentence bluebook's `PhraseSeed` rows, so
    # what an author may write in plain sentences is a table rather than code typed a second time.
    module PhraseTable
      extend Projector::Target

      projects_as :phrase_table, declares: "Phrase"

      # The bluebook the rows are declared in, read from the language's own tree.
      SENTENCE_FILE = File.expand_path("../language/sentence/sentence.bluebook", __dir__)

      # The ports and adapters a bare bluebook needs loaded before its predicates can be recovered.
      SUPPORT_FILES = %w[ports/persistence.port ports/extraction.port
                         adapters/driven/memory.adapter adapters/driven/prism.adapter]
                      .map { |path| File.expand_path("../#{path}", __dir__) }.freeze

      # The columns of a `PhraseRow`, in the order the Rust struct declares them.
      FIELDS = %i[id context pattern opens canonical status].freeze

      module_function

      # @param bluebook [Bluebook::Chapter] the Sentence bluebook
      # @param options [Hash{Symbol => Object}] ignored; present to satisfy the
      #   `Projector::Target` calling convention
      # @return [String] the rendered Rust source
      def call(bluebook:, options: {}) = render(bluebook)

      # Loads the Sentence bluebook on its own, in a registry of its own.
      #
      # @return [Bluebook::Chapter] the bluebook declared by `SENTENCE_FILE`
      def chapter
        registry = Hecks::Runtime::Registry.new
        Hecks.with_registry(registry) { (SUPPORT_FILES + [SENTENCE_FILE]).each { |file| Kernel.load(file) } }
        registry.bluebook("Sentence")
      end

      # @param bluebook [Bluebook::Chapter] the Sentence bluebook
      # @return [Array<Hash{Symbol => String}>] one row per declared phrase, every field a string
      #   and an omitted column read as its default
      def rows(bluebook)
        seed = bluebook.aggregate("Phrase").value_objects.find { |vo| vo.hecks_name == "PhraseSeed" }
        seed.members.map do |member|
          row = member.to_h.transform_values(&:to_s)
          FIELDS.to_h { |field| [field, row.fetch(field) { default(field) }] }
        end
      end

      # @param field [Symbol] a `FIELDS` member a row left out
      # @return [String] the column's default
      def default(field) = { canonical: "yes", status: "admitted" }.fetch(field, "")

      # @param row [Hash{Symbol => String}] one phrase, keyed by `FIELDS`
      # @return [String] one `PhraseRow { ... },` line
      def phrase_row(row)
        fields = FIELDS.map { |field| "#{field}: #{ParserTable.rust_string(row[field])}" }
        "    PhraseRow { #{fields.join(", ")} },"
      end

      # @param bluebook [Bluebook::Chapter] the Sentence bluebook
      # @return [String] the whole `phrases.rs`
      def render(bluebook)
        <<~RUST
          // GENERATED by hecks project_phrase_table from the Sentence chapter's PhraseSeed rows
          // (lib/hecks/language/sentence/sentence.bluebook) — DO NOT EDIT BY HAND.
          //
          // Re-run `hecks project_phrase_table` after any phrase change. The drift spec
          // (spec/phrase_table_spec.rb) fails the normal suite when this file goes stale.

          /// One sentence an author may write.
          #[derive(Debug, Clone, Copy)]
          pub struct PhraseRow {
              /// The phrase's name, which the sentence front end lowers by.
              pub id: &'static str,
              /// The block it is legal in: File, Domain, Aggregate, Has, ValueObject, Lifecycle,
              /// Command, Query or Condition for a domain; ExamplesFile, Examples, Background,
              /// Example, Step or Outcome for an examples file.
              pub context: &'static str,
              /// Literal words, `(a|an)` alternatives and `{slot:kind}` fill-ins.
              pub pattern: &'static str,
              /// The block this sentence opens, or "" for a plain line.
              pub opens: &'static str,
              /// "yes" for the one spelling the formatter writes.
              pub canonical: &'static str,
              pub status: &'static str,
          }

          impl PhraseRow {
              /// A retired phrase is refused like any unknown sentence.
              pub fn live(&self) -> bool {
                  matches!(self.status, "" | "admitted" | "deprecated")
              }
          }

          pub static PHRASES: &[PhraseRow] = &[
          #{rows(bluebook).map { |row| phrase_row(row) }.join("\n")}
          ];
        RUST
      end
    end
  end
end
