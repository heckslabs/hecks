# frozen_string_literal: true

require "fileutils"

module Hecks
  module Tools
    # The model check a domain repository runs in its CI, generated from Hecks' own definition of it:
    # the client profile, over the domain's bluebooks, from the hecks the Gemfile pins.
    #
    # A downstream repository commits the file this writes (`.github/workflows/model-check.yml`) and
    # never edits it; a change to the check is made here, and every repository regenerates from it.
    #
    #   ruby lib/hecks/tools/downstream_model_check.rb <checkout> <domain-directory> [--check]
    #
    # With `--check` nothing is written: the tool answers 1 when the committed file differs.
    module DownstreamModelCheck
      # Where the workflow lives under the checkout.
      FILE = ".github/workflows/model-check.yml"

      # The hecks profile the check runs under (Hecks' client profile, which refuses what the
      # client cannot answer for).
      PROFILE = "client"

      # The bluebook directory the check reads, relative to the domain directory.
      DOMAINS = "bluebook"

      # The Ruby the check runs on, matching the domain repositories' CI.
      RUBY_VERSION = "3.3"

      BANNER = "# Generated by hecks lib/hecks/tools/downstream_model_check.rb from Hecks' client-profile model " \
               "check. Do not edit; change the generator in hecks."

      module_function

      # @param domain_directory [String] the directory the domain's Gemfile and bluebooks live in,
      #   relative to the checkout (`.` when they are at the root)
      # @return [String] the workflow's text, ending in a newline
      def workflow(domain_directory:)
        <<~YAML
          #{BANNER}

          name: Model check

          on:
            pull_request:
            push:
              branches: [main]
            workflow_dispatch: {}

          permissions:
            contents: read

          jobs:
            model-check:
              runs-on: ubuntu-24.04
              timeout-minutes: 15
              steps:
                - uses: actions/checkout@93cb6efe18208431cddfb8368fd83d5badbf9bfd # v5

                - uses: ruby/setup-ruby@14594264cd68ce8a2345dd349bc3d138a4ef85c8 # v1
                  with:
                    ruby-version: "#{RUBY_VERSION}"
                    bundler-cache: false

                - name: Model check (hecks #{PROFILE} profile)
                  working-directory: #{domain_directory}
                  env:
                    HECKS_ENVIRONMENT: memory
                  run: |
                    bundle install --quiet --jobs 4
                    bundle exec hecks model_check_run.model_check! profile=#{PROFILE} domains=#{DOMAINS} --wait
        YAML
      end

      # Writes the workflow under `root`, or with `check` compares it and reports whether it is current.
      #
      # @param root [String] the checkout
      # @param domain_directory [String] see {workflow}
      # @param check [Boolean] compare without writing
      # @return [Integer] 0 when written or current, 1 when `check` finds the file out of date
      def main(root:, domain_directory:, check: false)
        path = File.join(root, FILE)
        text = workflow(domain_directory: domain_directory)
        current = File.file?(path) && File.read(path) == text
        return check_report(current, path) if check
        return puts("#{FILE}: already current") && 0 if current

        FileUtils.mkdir_p(File.dirname(path))
        File.write(path, text)
        puts "wrote #{FILE}"
        0
      end

      # @return [Integer] 0 when the file is current, else 1 with the reason on stderr
      def check_report(current, path)
        if current
          puts "#{FILE}: current"
          return 0
        end

        warn "#{FILE}: out of date at #{path} (regenerate with downstream_model_check.rb)"
        1
      end
    end
  end
end

if $PROGRAM_NAME == __FILE__
  root, domain_directory, flag = ARGV
  abort "usage: downstream_model_check.rb <checkout> <domain-directory> [--check]" unless root && domain_directory

  exit Hecks::Tools::DownstreamModelCheck.main(root: root, domain_directory: domain_directory,
                                               check: flag == "--check")
end
