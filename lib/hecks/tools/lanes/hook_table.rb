# frozen_string_literal: true

module Hecks
  module Tools
    module Lanes
      # The table the git pre-push hook reads to decide what a push runs, one line for each `Lane`
      # row. The hook is shell and boots no Ruby to decide, so the rows are projected into a file
      # it can read with `read`.
      module HookTable
        # Where the table lives, relative to the checkout.
        PATH = ".githooks/pre-push.lanes"

        # The word a line holds for an empty column, since `read` would otherwise merge the gaps.
        NONE = "-"

        module_function

        # @param lanes [Array<Hash{String => String}>] the `Lane` rows
        # @return [String] the table: `<lane> <push_gate> <full_gate> <train>` for each lane
        def text(lanes)
          header = [
            "# Generated by hecks project_lanes from the Lane rows of the Vocabulary bluebook. Do not hand-edit.",
            "# lane push_gate full_gate train (- is none)"
          ]
          rows = lanes.map { |lane| %w[name push_gate full_gate train].map { |key| cell(lane[key]) }.join(" ") }
          "#{(header + rows + attests).join("\n")}\n"
        end

        # @return [Array<String>] the line naming the checks a note the hook writes may stand in for
        def attests
          ["# the checks a signed note may stand in for, from the GateCheck rows marked attests",
           "@attests #{AttestedChecks.local.join(",")}"]
        end

        # @param value [String, nil] a column of a `Lane` row
        # @return [String] the value, or `-` when it is empty
        def cell(value) = value.to_s.empty? ? NONE : value.to_s
      end
    end
  end
end
