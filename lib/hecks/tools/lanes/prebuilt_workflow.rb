# frozen_string_literal: true

module Hecks
  module Tools
    module Lanes
      # The workflow that builds and publishes one `PrebuiltBinary` row (ADR 0110): after a push to
      # `main` that touches the row's crate, it builds the binary on the row's runner and, unless
      # a release for that key already exists, publishes it with its sha256. What the key is and
      # where a client looks is `Hecks::RustBuild::PrebuiltBinary`, not anything written here.
      module PrebuiltWorkflow
        module_function

        # @param row [Hash{String => String}] a `PrebuiltBinary` row
        # @return [String] the path of the workflow, relative to the checkout
        def path(row) = ".github/workflows/publish-#{row["name"]}.yml"

        # @param row [Hash{String => String}] a `PrebuiltBinary` row
        # @return [String] the workflow
        def text(row)
          [*header(row), *trigger(row), *job(row)].join("\n") << "\n"
        end

        def header(row)
          name = row["name"]
          ["name: Publish #{name}", "",
           "# Generated by hecks project_lanes from the PrebuiltBinary rows of the Vocabulary chapter. Do not hand-edit.",
           "#",
           "# Builds #{row["executable"]} from #{row["crate"]} for #{row["target"]} and publishes it as the release",
           "# #{name}-<key>, where the key is a hash of the crate's build inputs. A client that needs the same",
           "# bytes downloads it instead of compiling (Hecks::RustBuild::PrebuiltBinary); a key that already has a",
           "# release is left alone, so a push that changed nothing the build reads publishes nothing."]
        end

        def trigger(row)
          ["on:", "  push:", "    branches: [main]", "    paths:", "      - \"#{row["crate"]}/**\"",
           "      - \".github/workflows/publish-#{row["name"]}.yml\"",
           "      - \"lib/hecks/rust_build/prebuilt_binary.rb\"",
           "  workflow_dispatch: {}", "",
           "concurrency:", "  group: publish-#{row["name"]}", "  cancel-in-progress: false", "",
           "permissions:", "  contents: write", ""]
        end

        def job(row)
          ["jobs:", "  publish:", "    runs-on: #{row["runner"]}", "    timeout-minutes: 40", "    steps:",
           "      - uses: actions/checkout@v4", "      - uses: ./.github/actions/setup-ruby", *key_step(row),
           *build_steps(row), *release_step(row)]
        end

        def key_step(row)
          ["      - name: Name the release", "        id: key", "        run: |",
           "          key=$(bundle exec ruby -Ilib -rhecks/rust_build/prebuilt_binary -e \\",
           "            'puts Hecks::RustBuild::PrebuiltBinary.key(ARGV.fetch(0))' #{row["crate"]})",
           "          tag=#{row["name"]}-$key",
           "          echo \"tag=$tag\" >> \"$GITHUB_OUTPUT\"",
           "          if gh release view \"$tag\" > /dev/null 2>&1; then echo \"exists=true\" >> \"$GITHUB_OUTPUT\"; fi",
           "        env:", "          GH_TOKEN: ${{ github.token }}"]
        end

        def build_steps(row)
          ["      - name: Build #{row["executable"]}", "        if: steps.key.outputs.exists != 'true'",
           "        working-directory: #{row["crate"]}", "        run: |",
           "          rustup toolchain install stable --profile minimal",
           "          rustup run stable cargo build --release --target #{row["target"]} --bin #{row["executable"]}"]
        end

        def release_step(row)
          asset = "#{row["executable"]}-#{row["target"]}"
          ["      - name: Publish the release", "        if: steps.key.outputs.exists != 'true'",
           "        env:", "          GH_TOKEN: ${{ github.token }}", "          TAG: ${{ steps.key.outputs.tag }}",
           "        run: |",
           "          mkdir out",
           "          cp #{row["crate"]}/target/#{row["target"]}/release/#{row["executable"]} out/#{asset}",
           "          (cd out && sha256sum #{asset} > #{asset}.sha256)",
           "          gh release create \"$TAG\" out/#{asset} out/#{asset}.sha256 --prerelease --target \"$GITHUB_SHA\" \\",
           "            --title \"$TAG\" \\",
           "            --notes \"#{row["executable"]} for #{row["target"]}, built from #{row["crate"]} at $GITHUB_SHA.\""]
        end
      end
    end
  end
end
