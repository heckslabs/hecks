# frozen_string_literal: true

require "spec_helper"
require "tmpdir"
require "fileutils"
require "hecks/hecks/adapters/dispatching/held_ground"
require_relative "support/landing_claims_registry"

# A landing is refused when its branch takes lines out of files its item's area does not hold.
RSpec.describe Hecks::Adapters::GitLanding::Strays do
  let(:shell) { Hecks::Adapters::Shell.new }
  let(:repo) { Dir.mktmpdir("strays") }
  let(:own) { "lib/mine" }

  before do
    git("init", "-q", "-b", "main")
    write("lib/mine/a.rb" => "a\n", "lib/other/b.rb" => "1\n2\n3\n", "spec/other_spec.rb" => "x\n")
    write("lib/gen.rb" => "# Generated by x, do not edit\nold\n")
    git("add", ".")
    git("commit", "-q", "-m", "base")
    git("checkout", "-q", "-b", "work")
  end

  after { FileUtils.remove_entry(repo) }

  def git(*argv) = shell.capture("git", "-c", "user.name=t", "-c", "user.email=t@t", *argv, chdir: repo)

  def write(files)
    files.each do |path, text|
      FileUtils.mkdir_p(File.dirname(File.join(repo, path)))
      File.write(File.join(repo, path), text)
    end
  end

  def commit
    git("add", "-A")
    git("commit", "-q", "-m", "work")
  end

  def refusal(area: [own])
    allow(Hecks::Adapters::StartedWork).to receive(:items).and_return([{ key: "work", area: area }])
    git_stand_in = Object.new.tap do |stand|
      stand.define_singleton_method(:capture) { |*argv, **opts| Hecks::Adapters::Shell.new.capture("git", *argv, **opts) }
    end
    described_class.new(git_stand_in, repo, LandingClaimsRegistry.landing_claims_registry).refusal("work", "main")
  end

  it "refuses lines deleted from a file outside the area, naming it and the count" do
    write("lib/other/b.rb" => "1\n")
    commit

    expect(refusal).to include("lib/other/b.rb (2 lines)")
  end

  it "refuses a spec deleted outside the area" do
    FileUtils.rm(File.join(repo, "spec/other_spec.rb"))
    commit

    expect(refusal).to include("spec/other_spec.rb (1 lines)")
  end

  it "lets a branch that only adds outside its area through" do
    write("lib/other/new.rb" => "new\n", "lib/other/b.rb" => "1\n2\n3\n4\n")
    commit

    expect(refusal).to be_nil
  end

  it "lets deletions inside the area through" do
    write("lib/mine/a.rb" => "")
    commit

    expect(refusal).to be_nil
  end

  it "lets a deletion through when the item names the file in its area" do
    write("lib/other/b.rb" => "1\n")
    commit

    expect(refusal(area: [own, "lib/other/b.rb"])).to be_nil
  end

  it "does not judge a branch whose claim has no area" do
    write("lib/other/b.rb" => "1\n")
    commit

    expect(refusal(area: [])).to be_nil
  end

  it "does not judge a generated file" do
    write("lib/gen.rb" => "# Generated by x, do not edit\nnew\n")
    commit

    expect(refusal).to be_nil
  end

  it "counts a rename out of the area as a deletion" do
    FileUtils.mv(File.join(repo, "lib/other/b.rb"), File.join(repo, "lib/mine/b.rb"))
    commit

    expect(refusal).to include("lib/other/b.rb (3 lines)")
  end
end
