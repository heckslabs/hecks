require "spec_helper"
require "hecks/cli"
require "hecks/cli/project_cli"
require "json"
require "open3"
require "rbconfig"
require "tmpdir"
require "fileutils"

# The client-launcher smoke: a launcher written by `hecks project_cli` into a scratch copy of
# examples/pizzas (bound to Memory, nothing written in the checkout) runs as a client's shell
# would run it, in three forms.
#
# - **plain**: a domain that did not opt in keeps today's `command name=value` calls, refusals
#   that print their reason and exit 1, and `--help`.
# - **opted in**: a `launcher` world setting adds aliases, `--wait`, `--confirm` and run keys.
# - **2.9**: the text the 2.9 generator wrote names `Hecks::Doors::CliRunner` and
#   `install_doors: false`, and runs unchanged against the current runtime.
RSpec.describe "client launcher smoke" do
  # The launcher the 2.9 generator wrote for a domain at `pizzas/`, byte for byte.
  PRE_3_0_LAUNCHER = <<~RUBY.freeze
    #!/usr/bin/env ruby

    # Pizzas's command line — GENERATED by hecks project_cli. Do not edit.
    #
    # A launcher, not a CLI: the commands, their arguments and their refusals are
    # projected from the bluebook beside it every time this runs, so a change
    # to the chapter shows up here without re-minting anything.
    #
    #   pizzas/pizzas                  every command, and every question
    #   pizzas/pizzas <command> --help    what it wants, and how it refuses

    $LOAD_PATH.unshift File.expand_path("../lib", __dir__)

    require "hecks"

    runtime = begin
      Hecks.boot(__dir__, install_doors: false)
    rescue StandardError => e
      abort "cannot open Pizzas: \#{e.message.lines.first.strip}"
    end

    text, status = Hecks::Doors::CliRunner.call(
      runtime: runtime, argv: ARGV, program: "pizzas/pizzas"
    )
    status.zero? ? puts(text) : abort(text)
  RUBY

  CREATE = %w[order.create_pizza name=Margherita pizza.price_cents=900 pizza.size=large].freeze

  # Every call the plain and the pre-3.0 launcher answer alike.
  CALLS = {
    usage:         [],
    help:          %w[--help],
    verb_help:     %w[order.create_pizza --help],
    refusal_help:  %w[order.purchase --help],
    short:         CREATE,
    long:          %w[order.create_pizza name.value=Margherita pizza.price_cents.cents=900 pizza.size.value=large],
    qualified:     %w[order.create_pizza! name=Margherita pizza.price_cents=900 pizza.size=large],
    question:      %w[ask order.available],
    bare_question: %w[order.available],
    invariant:     %w[order.create_pizza name=Margherita pizza.price_cents=900 pizza.size=huge],
    missing:       %w[order.purchase to=nope amount=5],
    unknown:       %w[order.create_piza],
    bare:          %w[create_pizza name=Margherita pizza.price_cents=900 pizza.size=large],
    bad_word:      %w[order.create_pizza nonsense=1],
    wait_unset:    CREATE + %w[--wait],
    confirm_unset: CREATE + %w[--confirm]
  }.freeze

  def self.scratch
    @scratch ||= Dir.mktmpdir("client_launcher_smoke")
  end

  # A copy of examples/pizzas under `name`, bound to Memory, with `lib/` linked in so the launcher's
  # `$LOAD_PATH` line finds this checkout.
  def self.client(name, world: nil, bluebook: nil)
    root = File.join(scratch, name)
    copy_pizzas(root)
    dir = File.join(root, "pizzas/bluebook")
    bind_to_memory(dir, world)
    rewrite_bluebook(File.join(dir, "pizzas.bluebook"), bluebook) if bluebook
    root
  end

  def self.copy_pizzas(root)
    FileUtils.mkdir_p(root)
    FileUtils.cp_r(File.join(InMemoryDomain::ROOT, "examples/pizzas"), File.join(root, "pizzas"))
    File.symlink(File.join(InMemoryDomain::ROOT, "lib"), File.join(root, "lib"))
  end

  # Rebinds the copy's hecksagon to Memory and writes its world, with `world` as an extra setting.
  def self.bind_to_memory(dir, world)
    hecksagon = File.join(dir, "pizzas.hecksagon")
    File.write(hecksagon, File.read(hecksagon).gsub("PostgresEra", "Memory"))
    File.write(File.join(dir, "pizzas.world"), <<~RUBY)
      Hecks.world "Pizzas" do
        realm "Examples"
        persisted_by("Memory")
        #{world}
      end
    RUBY
  end

  def self.rewrite_bluebook(path, edit) = File.write(path, edit.call(File.read(path)))

  # The bluebook with a `Run` value object, an optional Boolean `confirm` on CreatePizza, and
  # the `available` state marked as a failure.
  def self.add_run_and_confirm(text)
    extra = "attribute :pizza, Pizza\n      attribute :confirm, Boolean, optional: true\n      " \
            "attribute :run, Run\n"
    run   = "value_object \"Run\" do\n      attribute :value, String\n    end\n\n    " \
            "value_object \"Pizza\" do"
    marked = text.sub("default: \"available\" do\n", "default: \"available\" do\n      mark :failure, \"available\"\n")
    marked.sub("attribute :pizza, Pizza\n", extra).sub('value_object "Pizza" do', run)
  end

  # Runs one launcher call in its own process, as a client's shell would.
  def self.launch(root, argv)
    env = { "HECKS_ENVIRONMENT" => "memory" }
    out, err, status = Open3.capture3(env, RbConfig.ruby, "pizzas/pizzas", *argv, chdir: root)
    { out: out, err: err, status: status.exitstatus }
  end

  # Runs each call in a process of its own, four at a time.
  def self.launch_all(root, calls)
    calls.each_slice(4).flat_map do |slice|
      slice.map { |name, argv| Thread.new { [name, launch(root, argv)] } }.map(&:value)
    end.to_h
  end

  def self.generate(root)
    ENV["HECKS_ENVIRONMENT"] ||= "memory"
    Hecks::CLI::ProjectCli.call(%w[pizzas], program: "hecks project_cli", root: root, remove_stale_bin: false)
  end

  before(:all) do
    @plain_root = self.class.client("plain")
    @out = capture_stdout { self.class.generate(@plain_root) }
    @plain = self.class.launch_all(@plain_root, CALLS)

    @old_root = self.class.client("pre_3_0")
    File.write(File.join(@old_root, "pizzas/pizzas"), PRE_3_0_LAUNCHER)
    FileUtils.chmod("+x", File.join(@old_root, "pizzas/pizzas"))
    @old = self.class.launch_all(@old_root, CALLS)

    @opted_root = self.class.client(
      "opted_in",
      world:    'launcher "Launcher", run_keys: true, names: { "make" => "order.create_pizza" }',
      bluebook: self.class.method(:add_run_and_confirm)
    )
    capture_stdout { self.class.generate(@opted_root) }
    opted_calls = {
      alias:      %w[make name=A pizza.price_cents=1 pizza.size=small],
      alias_help: %w[make --help],
      listed:     [],
      plain:      %w[order.create_pizza name=B pizza.price_cents=1 pizza.size=small],
      wait:       %w[order.create_pizza name=C pizza.price_cents=1 pizza.size=small --wait],
      confirm:    %w[order.create_pizza name=D pizza.price_cents=1 pizza.size=small --confirm],
      run_given:  %w[order.create_pizza name=E pizza.price_cents=1 pizza.size=small run=mine-1],
      wait_bad:   %w[ask order.available --wait]
    }
    @opted = self.class.launch_all(@opted_root, opted_calls)
  end

  after(:all) { FileUtils.rm_rf(self.class.scratch) }

  def capture_stdout
    saved = $stdout
    $stdout = StringIO.new
    yield
    $stdout.string
  ensure
    $stdout = saved
  end

  def created(result)
    expect(result[:status]).to eq(0), result.inspect
    JSON.parse(result[:out])
  end

  shared_examples "today's forms" do |ivar|
    let(:results) { instance_variable_get(ivar) }

    it "lists every command and question with no arguments, and on --help", :aggregate_failures do
      %i[usage help].each do |call|
        expect(results[call][:status]).to eq(0)
        expect(results[call][:out]).to include("create_pizza", "add_topping", "purchase", "available")
      end
      expect(results[:usage][:out]).to eq(results[:help][:out])
    end

    it "says what a command wants and how it refuses", :aggregate_failures do
      expect(results[:verb_help][:out]).to include("dispatches Pizzas::Order.CreatePizza", "name.value")
      expect(results[:refusal_help][:out]).to include("refused when:", "the payment covers the price")
      expect(results[:refusal_help][:status]).to eq(0)
    end

    it "runs `command name=value` with short and long argument spellings and a trailing `!` alike", :aggregate_failures do
      answers = %i[short long qualified].map { |call| created(results[call]) }

      expect(answers.map { |a| a["id"] }).to all(eq("Margherita"))
      expect(answers.map { |a| a["events"] }).to all(eq(["PizzaCreated"]))
      expect(answers.first.dig("state", "pizza", "size", "value")).to eq("large")
      expect(answers.first.dig("state", "status")).to eq("available")
    end

    it "answers a question with and without `ask`", :aggregate_failures do
      expect(created(results[:question])).to eq([])
      expect(created(results[:bare_question])).to eq([])
    end

    it "prints the domain's own reason and exits 1 when a value is refused", :aggregate_failures do
      expect(results[:invariant][:status]).to eq(1)
      expect(results[:invariant][:err]).to include('Size admits "small", "large" — got "huge"')
      expect(results[:invariant][:out]).to be_empty
    end

    it "points at --help and exits 1 for a record that is not there", :aggregate_failures do
      expect(results[:missing][:status]).to eq(1)
      expect(results[:missing][:err]).to include('no Order with name.value "nope"', "purchase --help")
    end

    it "suggests the near name and exits 1 for an unknown command", :aggregate_failures do
      expect(results[:unknown][:status]).to eq(1)
      expect(results[:unknown][:err]).to include("no such command: order.create_piza", "did you mean:", "  order.create_pizza")
    end

    it "refuses a bare command name, pointing at the one qualified by its aggregate", :aggregate_failures do
      expect(results[:bare][:status]).to eq(1)
      expect(results[:bare][:err]).to include("no such command: create_pizza", "did you mean:", "  order.create_pizza")
    end

    it "names the argument and exits 1 for a word the command does not take", :aggregate_failures do
      expect(results[:bad_word][:status]).to eq(1)
      expect(results[:bad_word][:err]).not_to be_empty
    end

    it "refuses --wait and --confirm, as flags the command lacks, when the domain did not opt in", :aggregate_failures do
      expect(results[:confirm_unset][:status]).to eq(1)
      expect(results[:wait_unset][:status]).to eq(1)
      expect(results[:wait_unset][:err]).to include("--wait is a flag, but this command has no Boolean argument")
    end
  end

  describe "a launcher the current generator wrote for a domain that did not opt in" do
    it "is the launcher the 2.9 generator wrote, byte for byte", :aggregate_failures do
      expect(File.read(File.join(@plain_root, "pizzas/pizzas"))).to eq(PRE_3_0_LAUNCHER)
      expect(@out).to include("pizzas/pizzas  ->  Pizzas")
      expect(File.executable?(File.join(@plain_root, "pizzas/pizzas"))).to be(true)
    end

    it_behaves_like "today's forms", :@plain
  end

  describe "a launcher the 2.9 generator wrote, run against the current runtime" do
    it "embeds the names a Facade rename must keep answering" do
      text = File.read(File.join(@old_root, "pizzas/pizzas"))

      expect(text).to include("Hecks::Doors::CliRunner.call", "install_doors: false")
    end

    it_behaves_like "today's forms", :@old

    it "answers exactly what the regenerated launcher answers" do
      CALLS.each_key do |call|
        expect(@old[call]).to eq(@plain[call]), call.to_s
      end
    end
  end

  describe "a domain that opted in through its world's launcher setting" do
    it "answers an alias, noted beside the command it stands for, and the full name too", :aggregate_failures do
      expect(created(@opted[:alias])["id"]).to eq("A")
      expect(@opted[:alias_help][:out]).to include("dispatches Pizzas::Order.CreatePizza")
      expect(@opted[:listed][:out]).to match(/^  order\.create_pizza! .*\(also: make!\)/)
      expect(@opted[:listed][:out]).not_to match(/^  make! /)
      expect(@opted[:plain][:status]).to eq(0)
    end

    it "mints the run key of a creating command given none, and keeps an explicit one", :aggregate_failures do
      expect(created(@opted[:plain]).fetch("run")).to match(/\A\h{8}-\h{4}-/)
      expect(created(@opted[:run_given])).not_to have_key("run")
    end

    it "reads --confirm as the Boolean argument of that name, and refuses it where there is none", :aggregate_failures do
      expect(created(@opted[:confirm])["id"]).to eq("D")
      expect(@plain[:confirm_unset][:status]).to eq(1)
      expect(@plain[:confirm_unset][:err]).to include("--confirm is a flag, but this command has no Boolean")
    end

    it "exits 1 under --wait when the record settles in a failure state, printing that state", :aggregate_failures do
      expect(@opted[:wait][:status]).to eq(1)
      expect(JSON.parse(@opted[:wait][:out]).dig("state", "status")).to eq("available")
      expect(@opted[:plain][:status]).to eq(0)
    end

    it "takes --wait out of a question's words too, and answers it" do
      expect(created(@opted[:wait_bad])).to eq([])
    end
  end
end
